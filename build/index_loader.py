"""Load entries/_index.yaml and expose slug -> id / slug -> file lookups.

The index is an ordered list of {slug, file} entries. Position determines
the SQL `_id`: the Nth entry (0-indexed) gets id BASE_ID + N. See
``build/renumber_yaml.py`` for how the index is maintained.
"""

from pathlib import Path
from typing import Dict, List, Optional, Tuple

import yaml

BASE_ID = 10000
INDEX_FILENAME = '_index.yaml'


def index_path(data_dir: Path) -> Path:
    return data_dir / 'entries' / INDEX_FILENAME


def load_index(data_dir: Path) -> List[Dict[str, str]]:
    """Return the raw ordered list from ``entries/_index.yaml``.

    Empty list if the file is missing (callers should fall back to the
    legacy ``_original_id`` field during the transition).
    """
    path = index_path(data_dir)
    if not path.exists():
        return []
    with open(path, 'r', encoding='utf-8') as f:
        data = yaml.safe_load(f)
    if not data:
        return []
    return data


def slug_to_id(index: List[Dict[str, str]]) -> Dict[str, int]:
    return {entry['slug']: BASE_ID + i for i, entry in enumerate(index)}


def slug_to_file(index: List[Dict[str, str]]) -> Dict[str, str]:
    return {entry['slug']: entry['file'] for entry in index}


def entry_sort_key(entry: Dict, id_map: Dict[str, int]) -> Tuple[int, str]:
    """Sort key for a YAML entry using the index.

    Falls back to ``_original_id`` for entries not yet in the index (during
    the transition) so mixed states remain buildable.
    """
    slug = entry.get('slug', '')
    if slug in id_map:
        return (0, id_map[slug])
    return (1, entry.get('_original_id', 0))


def entry_id(entry: Dict, id_map: Dict[str, int]) -> Optional[int]:
    """Return the SQL `_id` for an entry, or ``None`` if unknown."""
    slug = entry.get('slug', '')
    if slug in id_map:
        return id_map[slug]
    original = entry.get('_original_id')
    return int(original) if original else None


def entry_file(entry: Dict, file_map: Dict[str, str]) -> str:
    """Return the origin XML file for an entry, or empty if unknown."""
    slug = entry.get('slug', '')
    if slug in file_map:
        return file_map[slug]
    return entry.get('_original_file', '') or ''


def write_index(data_dir: Path, index: List[Dict[str, str]]) -> None:
    """Write ``entries/_index.yaml`` with one entry per line.

    The compact flow style keeps diffs to a single inserted line when a new
    entry is added at any position.
    """
    path = index_path(data_dir)
    path.parent.mkdir(parents=True, exist_ok=True)
    lines = [
        '# Ordered index of every entry in entries/. Position N (0-indexed)',
        f'# assigns SQL _id = {BASE_ID} + N. Regenerated by',
        '# build/renumber_yaml.py; only this file changes when IDs shift, so',
        '# per-entry YAML files stay churn-free across renumbering.',
    ]
    for item in index:
        slug = item['slug']
        file = item['file']
        lines.append('- {slug: %s, file: %s}' % (yaml_scalar(slug), yaml_scalar(file)))
    path.write_text('\n'.join(lines) + '\n', encoding='utf-8')


def yaml_scalar(value: str) -> str:
    """Emit a YAML scalar, quoting only when necessary.

    Slugs can contain apostrophes (from Klingon glottal stops) which need
    single-quoting in flow context.
    """
    needs_quote = False
    if not value:
        needs_quote = True
    elif value[0] in "!&*[]{}|>'\"%@`,#? -":
        needs_quote = True
    elif any(c in value for c in ":,'\"[]{}#&*!|>%@`"):
        needs_quote = True
    if needs_quote:
        escaped = value.replace("'", "''")
        return f"'{escaped}'"
    return value
